#!/bin/zsh
# Installs md2pdf:
#   1. npm dependencies
#   2. ~/.local/bin/md2pdf command-line launcher
#   3. "Convert to PDF" Finder Quick Action (right-click a .md file → Quick Actions)
#   4. ⌃⌥⌘P keyboard shortcut for the Quick Action
# Safe to re-run, e.g. after moving this folder or changing Node versions.

set -euo pipefail

ROOT=${0:A:h}
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/md2pdf"
SERVICES="$HOME/Library/Services"
WORKFLOW="$SERVICES/Convert to PDF.workflow"

NODE=$(command -v node) || { echo "Node.js is required: https://nodejs.org or 'brew install node'" >&2; exit 1; }

echo "→ Installing dependencies"
(cd "$ROOT" && npm install --silent --omit=dev)

echo "→ Installing launcher at $LAUNCHER"
mkdir -p "$BIN_DIR"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# Generated by $ROOT/install.sh
# The Node path is pinned so this works from Finder, which doesn't load your shell profile.
NODE="$NODE"
[ -x "\$NODE" ] || NODE=\$(command -v node) || { echo "md2pdf: node not found; re-run $ROOT/install.sh" >&2; exit 1; }
exec "\$NODE" "$ROOT/bin/md2pdf.js" "\$@"
EOF
chmod +x "$LAUNCHER"

echo "→ Installing Quick Action at $WORKFLOW"
mkdir -p "$SERVICES"
rm -rf "$WORKFLOW"
cp -R "$ROOT/quick-action/Convert to PDF.workflow" "$WORKFLOW"
# Point the workflow at convert.sh (XML-escape & in case the path contains one).
script_path=${ROOT//&/&amp;}/quick-action/convert.sh
/usr/bin/sed -i '' "s|__CONVERT_SCRIPT__|${script_path//|/\\|}|" "$WORKFLOW/Contents/document.wflow"
/System/Library/CoreServices/pbs -update 2>/dev/null || true

# Keyboard shortcut, stored in the Services preferences (System Settings → Keyboard →
# Keyboard Shortcuts → Services). Modifiers: @ = ⌘, ~ = ⌥, ^ = ⌃, $ = ⇧.
# Override with MD2PDF_SHORTCUT='@$p' ./install.sh, or MD2PDF_SHORTCUT= to skip.
SHORTCUT=${MD2PDF_SHORTCUT-'@~^p'}
if [[ -n "$SHORTCUT" ]]; then
  echo "→ Setting keyboard shortcut $SHORTCUT"
  prefs=$(mktemp -t md2pdf-pbs)
  defaults export pbs "$prefs"
  plutil -extract NSServicesStatus raw "$prefs" >/dev/null 2>&1 || plutil -insert NSServicesStatus -dictionary "$prefs"
  plutil -replace "NSServicesStatus.(null) - Convert to PDF - runWorkflowAsService" -json \
    "{\"key_equivalent\":\"$SHORTCUT\",\"presentation_modes\":{\"ContextMenu\":true,\"FinderPreview\":true,\"ServicesMenu\":true,\"TouchBar\":false}}" \
    "$prefs"
  defaults import pbs "$prefs"
  rm -f "$prefs"
  /System/Library/CoreServices/pbs -update 2>/dev/null || true
fi

if [[ ":$PATH:" != *":$BIN_DIR:"* ]]; then
  echo
  echo "Note: $BIN_DIR is not on your PATH. Add this to ~/.zshrc:"
  echo "  export PATH=\"\$HOME/.local/bin:\$PATH\""
fi

echo
echo "Done. Try:  md2pdf $ROOT/test/fixtures/sample.md"
echo "Or right-click a .md file in Finder → Quick Actions → Convert to PDF"
echo "Change the PDF style with:  $ROOT/set-style.sh"
